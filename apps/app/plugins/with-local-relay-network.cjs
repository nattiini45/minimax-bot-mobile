/**
 * Splits the cleartext permission between the development build and the release.
 *
 * The app talks to its relay over TLS in production (`https://`/`wss://`). A relay
 * that runs locally — `wrangler dev` on the developer's laptop, or the same thing
 * reached from an Android device through `adb reverse` — speaks plain HTTP on the
 * loopback interface, and Android blocks cleartext by default for apps that
 * target API 28 or later. This app targets API 36.
 *
 * The exception is a development convenience, so it belongs to the development
 * build only:
 *
 *   - `src/main` carries the strict configuration. Every build that is not a
 *     development build — the release APK among them — forbids cleartext
 *     outright, so the device token can never travel in the clear in a build
 *     anybody can install.
 *   - `src/debug` and `src/debugOptimized` carry the same resource with the
 *     loopback exception, so the development builds can still reach a relay on
 *     the developer's own machine.
 *
 * Android merges the build-type source set over the main one, so the debug build
 * gets the exception and the release build gets the strict configuration. The
 * manifest does not have to change: `android:networkSecurityConfig` names the
 * resource, and the resource has the same name in both source sets.
 *
 * Rather than switching cleartext on globally with `usesCleartextTraffic="true"`,
 * which would let the app talk to any host in the clear, the exception names the
 * loopback interface only, and TLS stays mandatory everywhere else.
 */

const fs = require('node:fs/promises');
const path = require('node:path');

const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

/**
 * The configuration the release build ships.
 *
 * No domain-config at all: a domain-config is an exception, and the release build
 * may not have one.
 */
const RELEASE_NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by plugins/with-local-relay-network.cjs.

  The release build does not permit cleartext anywhere. A relay running on the
  developer's own machine is reached from the development builds, which carry
  their own copy of this file with the loopback exception.
-->
<network-security-config>
    <base-config cleartextTrafficPermitted="false" />
</network-security-config>
`;

/**
 * The configuration the debug build ships.
 *
 * Cleartext is allowed for the loopback names only, because that is where a relay
 * running on the developer's own machine lives. Every other destination still has
 * to use TLS.
 */
const LOCAL_RELAY_NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by plugins/with-local-relay-network.cjs.

  Cleartext is allowed for the loopback interface only, because that is where a
  relay running on the developer's own machine lives. Every other destination
  still has to use TLS.

  This is a development source set's copy of the resource: it is merged over the
  main one in the development builds, and it is not part of the release build.
-->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">localhost</domain>
        <domain includeSubdomains="false">127.0.0.1</domain>
    </domain-config>
    <base-config cleartextTrafficPermitted="false" />
</network-security-config>
`;

/**
 * The two copies of the resource, and the source set each one belongs to.
 *
 * The order matters: the main source set is the one every build inherits, so it
 * has to hold the strict configuration.
 *
 * React Native's Gradle plugin registers a `debugOptimized` build type with a
 * source set of its own, and that source set does not inherit the debug one.
 * A build that is optimised for speed is still a development build, so it keeps
 * the loopback exception as well — without this, a developer who runs the
 * optimised build cannot reach a relay on their own machine.
 */
const SOURCE_SETS = [
  { sourceSet: 'main', config: RELEASE_NETWORK_SECURITY_CONFIG },
  { sourceSet: 'debug', config: LOCAL_RELAY_NETWORK_SECURITY_CONFIG },
  { sourceSet: 'debugOptimized', config: LOCAL_RELAY_NETWORK_SECURITY_CONFIG },
];

/**
 * Writes both copies of the network security config into the Android project.
 *
 * @param {string} platformProjectRoot the root of the generated Android project
 * @returns {Promise<string[]>} the paths that were written
 */
async function writeNetworkSecurityConfigs(platformProjectRoot) {
  const written = [];
  for (const { sourceSet, config } of SOURCE_SETS) {
    const target = path.join(
      platformProjectRoot,
      'app',
      'src',
      sourceSet,
      'res',
      'xml',
      'network_security_config.xml',
    );
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, config, 'utf8');
    written.push(target);
  }
  return written;
}

module.exports = function withLocalRelayNetwork(config) {
  config = withAndroidManifest(config, (config) => {
    const application = config.modResults.manifest.application?.[0];
    if (application) {
      application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    }
    return config;
  });

  config = withDangerousMod(config, [
    'android',
    async (config) => {
      await writeNetworkSecurityConfigs(config.modRequest.platformProjectRoot);
      return config;
    },
  ]);

  return config;
};

module.exports.RELEASE_NETWORK_SECURITY_CONFIG = RELEASE_NETWORK_SECURITY_CONFIG;
module.exports.LOCAL_RELAY_NETWORK_SECURITY_CONFIG = LOCAL_RELAY_NETWORK_SECURITY_CONFIG;
module.exports.writeNetworkSecurityConfigs = writeNetworkSecurityConfigs;
