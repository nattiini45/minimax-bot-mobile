/**
 * Permits cleartext traffic to a relay running on the developer's own machine.
 *
 * The app talks to its relay over TLS in production (`https://`/`wss://`). A relay
 * that runs locally — `wrangler dev` on the developer's laptop, or the same thing
 * reached from an Android emulator through `adb reverse` — speaks plain HTTP on the
 * loopback interface, and Android blocks cleartext by default from API 28 onwards.
 *
 * Rather than switching cleartext on globally with `usesCleartextTraffic="true"`,
 * which would let the app talk to any host in the clear, this writes a network
 * security config that permits cleartext for the loopback names only and keeps TLS
 * mandatory everywhere else.
 */

const fs = require('node:fs/promises');
const path = require('node:path');

const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const NETWORK_SECURITY_CONFIG = `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by plugins/with-local-relay-network.js.

  Cleartext is allowed for the loopback interface only, because that is where a
  relay running on the developer's own machine lives. Every other destination
  still has to use TLS.
-->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="false">localhost</domain>
        <domain includeSubdomains="false">127.0.0.1</domain>
    </domain-config>
    <base-config cleartextTrafficPermitted="false" />
</network-security-config>
`;

module.exports = function withLocalRelayNetwork(config) {
  config = withAndroidManifest(config, (config) => {
    const application = config.modResults.manifest.application?.[0];
    if (application) {
      application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    }
    return config;
  });

  config = withDangerousMod(config, [
    'android',
    async (config) => {
      const target = path.join(
        config.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml',
        'network_security_config.xml',
      );
      await fs.mkdir(path.dirname(target), { recursive: true });
      await fs.writeFile(target, NETWORK_SECURITY_CONFIG, 'utf8');
      return config;
    },
  ]);

  return config;
};
